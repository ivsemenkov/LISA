"""CLI argument parsing for LISA training."""

import argparse
import torch

from lisa.utils.constants import (
    CHECKPOINT_NAME,
    CLEAN_DATA_DIR,
    EXPERIMENTS_DIR,
    N_FEATURES,
    N_MEG_CHANNELS,
    PREPROCESSED_DATA_DIR,
)
from lisa.utils.validators import validate_run_group


def parse_bands(value: str) -> list[tuple[float, float]]:
    """Parse frequency bands from a comma-separated string.

    Example:
        "1-4,4-8,8-12" -> [(1.0, 4.0), (4.0, 8.0), (8.0, 12.0)]
    """
    bands = []
    for part in value.split(','):
        try:
            low, high = map(float, part.split('-'))
            bands.append((low, high))
        except (ValueError, TypeError):
            raise argparse.ArgumentTypeError(
                f"Invalid band format: '{part}'. Use 'low-high' format (e.g., '100-300')"
            )
    return bands


def parse_story_sounds(value: str) -> list[tuple[int, int]]:
    """Parse comma-separated validation story/sound pairs.

    Example:
        "3:4,2:7" -> [(3, 4), (2, 7)]
    """
    story_sounds = []
    for part in value.split(','):
        part = part.strip()
        if not part:
            continue
        try:
            story_id, sound_id = map(int, part.split(':'))
        except (ValueError, TypeError):
            raise argparse.ArgumentTypeError(
                f"Invalid story/sound format: '{part}'. Use 'story_id:sound_id' "
                "format (e.g., '3:4')."
            )
        if story_id < 0 or sound_id < 0:
            raise argparse.ArgumentTypeError(
                f"Invalid story/sound value: '{part}'. IDs must be non-negative."
            )
        story_sounds.append((story_id, sound_id))
    if not story_sounds:
        raise argparse.ArgumentTypeError(
            '--val-story-sounds must contain at least one story_id:sound_id pair.'
        )
    if len(set(story_sounds)) != len(story_sounds):
        raise argparse.ArgumentTypeError(
            f'--val-story-sounds contains duplicate pairs: {value!r}.'
        )
    return story_sounds


def parse_experiment_arguments(argv: list[str] | None = None) -> dict:
    """Parse CLI arguments into a plain dictionary.

    Args:
        argv: Optional list of CLI tokens (default: sys.argv).

    Returns:
        Dictionary of hyperparameters and runtime options.
    """
    parser = argparse.ArgumentParser(
        description='Training a MEG retrieval model', allow_abbrev=False
    )

    # Device
    parser.add_argument(
        '--device', type=str, default='cuda', help="Device to use: 'cpu' or 'cuda[:N]'."
    )

    # Data arguments
    parser.add_argument(
        '--batch-size', type=int, default=100, help='Training batch size.'
    )
    parser.add_argument(
        '--test-batch-size',
        type=int,
        default=20,
        help='Test/validation batch size. Default: 20.',
    )
    parser.add_argument('--meg-sr', type=int, default=100)
    parser.add_argument('--meg-offset', type=float, default=0.15)
    parser.add_argument(
        '--val-story-sounds',
        type=parse_story_sounds,
        default=parse_story_sounds('3:4'),
        help='Validation story/sound pairs held out from train, formatted as '
        '"story_id:sound_id[,story_id:sound_id...]". Default: "3:4".',
    )
    parser.add_argument(
        '--dirprocess',
        type=str,
        default=PREPROCESSED_DATA_DIR,
        help='Root directory with preprocessed embeddings/metadata.',
    )
    parser.add_argument(
        '--meg-files-dir',
        type=str,
        default=CLEAN_DATA_DIR,
        help='Root directory of MEG files (clean or raw).',
    )
    parser.add_argument(
        '--meg-format',
        type=str,
        default='fif',
        choices=('bids', 'fif'),
        help='MEG file format: fif (clean) or bids (raw MASC-MEG).',
    )
    parser.add_argument(
        '--embedding-layers',
        type=int,
        default=4,
        help='Number of Wav2Vec2 layers used in embeddings (must match files generated by lisa-generate-embeddings). Default: 4 (used in paper).',
    )
    parser.add_argument(
        '--window-tag',
        type=str,
        default='',
        help='Segment-length ablation tag selecting alternative embeddings/dataframe '
        'files produced by lisa-regen-windows (e.g. "w5"). Empty (default) uses the '
        'canonical 3-second files, so runs are identical to the baseline. When set, '
        'training loads extract_features_{split}{layers}_{tag}.npy and '
        'df_{split}{N}_{tag}.csv from the same --dirprocess (MEG npz is shared).',
    )
    parser.add_argument(
        '--feature-reduction',
        type=str,
        default='none',
        choices=('none', 'pca', 'linear'),
        help='Feature-axis reduction mode. PCA is audio-only preprocessing; linear keeps audio/MEG trainable.',
    )
    parser.add_argument(
        '--feature-reduction-dim',
        type=int,
        default=None,
        help='Reduced feature dimension for --feature-reduction. Required unless --feature-reduction=none.',
    )
    parser.add_argument(
        '--time-reduction',
        type=str,
        default='none',
        choices=(
            'none',
            'pca',
            'linear',
            'mean',
            'max',
            'adaptive_avg',
            'adaptive_max',
            'attn',
            'gated_attn',
            'query_attn',
        ),
        help='Time-axis reduction mode. PCA is audio-only preprocessing; all other modes use the same in-model time-reduction module on audio and/or MEG as appropriate.',
    )
    parser.add_argument(
        '--time-reduction-dim',
        type=int,
        default=None,
        help='Reduced/output time length for --time-reduction. Required for pca, linear, adaptive pooling, and query attention.',
    )
    parser.add_argument(
        '--time-reduction-hidden-dim',
        type=int,
        default=None,
        help='Hidden size for attention-style time reduction (attn, gated_attn).',
    )
    parser.add_argument(
        '--time-reduction-num-heads',
        type=int,
        default=1,
        help='Number of heads for query-attention time reduction.',
    )

    # Model arguments - Spatial
    parser.add_argument('--n-channels-attention', type=int, default=270)
    parser.add_argument('--n-channels-unmix', type=int, default=25)
    parser.add_argument(
        '--use-spatial-attention',
        type=str,
        default='3D',
        choices=('2D', '3D', 'none'),
        help='Type of spatial attention: 2D (Fourier), 3D (spherical harmonics), or none (disabled).',
    )
    parser.add_argument(
        '--use-unmixing-layer',
        action=argparse.BooleanOptionalAction,
        default=True,
        help='Enable the 1x1 unmixing layer inside the spatial module.',
    )
    parser.add_argument(
        '--use-subject-layer',
        action=argparse.BooleanOptionalAction,
        default=True,
        help='Enable the subject-specific layer inside the spatial module.',
    )
    parser.add_argument('--n-spatial-harmonics', type=int, default=24)
    parser.add_argument(
        '--spatial-dropout-number',
        type=int,
        default=0,
        help='Number of spatial dropout centers (0 to disable).',
    )
    parser.add_argument(
        '--spatial-dropout-radius',
        type=float,
        default=0.1,
        help='Radius for spatial dropout.',
    )
    parser.add_argument(
        '--dropout-center-low',
        type=float,
        default=0.1,
        help='Lower bound for spatial dropout center sampling range in coords_xy space.',
    )
    parser.add_argument(
        '--dropout-center-high',
        type=float,
        default=0.9,
        help='Upper bound for spatial dropout center sampling range in coords_xy space.',
    )

    # Model arguments - Temporal filter
    parser.add_argument(
        '--temporal-filter-type',
        type=str,
        default='conv',
        choices=('conv', 'filtfilt'),
        help='Type of temporal filter: conv or filtfilt (zero-phase).',
    )
    parser.add_argument(
        '--temporal-filter-padding-mode',
        type=str,
        default='zeros',
        choices=('zeros', 'reflect', 'replicate', 'circular'),
        help='Padding mode for temporal filter.',
    )
    parser.add_argument(
        '--temporal-filter-bands',
        type=parse_bands,
        default=None,
        help='Frequency bands for FIR initialization (Hz). If None, no FIR initialization. Format: low1-high1,low2-high2',
    )
    parser.add_argument(
        '--temporal-filter-freeze',
        action=argparse.BooleanOptionalAction,
        default=False,
        help='Freeze temporal filter weights after initialization.',
    )
    parser.add_argument(
        '--temporal-filter-kernel-size',
        type=int,
        default=15,
        help='Kernel size of temporal filter in samples.',
    )

    # Model arguments - Temporal gating
    parser.add_argument(
        '--tf-gated',
        action=argparse.BooleanOptionalAction,
        default=False,
        help='Enable residual gate: y = x + sigmoid(gamma) * (Conv(x) - x)',
    )
    parser.add_argument(
        '--tf-gate-per-channel',
        action=argparse.BooleanOptionalAction,
        default=False,
        help='Learn per-channel gate (gamma vector) instead of scalar.',
    )
    parser.add_argument(
        '--tf-gate-init-alpha',
        type=float,
        default=0.05,
        help='Initial alpha for temporal gate (in [0,1]).',
    )
    parser.add_argument(
        '--tf-gelu',
        action=argparse.BooleanOptionalAction,
        default=False,
        help='Enable GELU activation after temporal filtering in spatial module.',
    )

    # Model arguments - Temporal tail
    parser.add_argument(
        '--n-channels-block',
        type=str,
        default='auto',
        help="Number of channels in temporal conv blocks, or 'auto' to match --n-channels-unmix.",
    )
    parser.add_argument(
        '--n-temporal-module-blocks',
        type=int,
        default=2,
        help='Number of temporal conv blocks (0 for no temporal module).',
    )
    parser.add_argument(
        '--head-pool',
        type=str,
        default='single_conv',
        choices=('conv', 'single_conv'),
        help='Pooling type for projection head.',
    )
    parser.add_argument('--head-stride', type=int, default=2)

    # Trainer arguments
    parser.add_argument(
        '--seed',
        type=str,
        default='42',
        help="Random seed, or 'none' for an unseeded run.",
    )
    parser.add_argument(
        '--torch-deterministic',
        action=argparse.BooleanOptionalAction,
        default=False,
        help='Use deterministic CUDA/cuDNN (reproducible; slower). Default: False (faster convs).',
    )
    parser.add_argument('--dl-n-workers', type=int, default=0)
    parser.add_argument('--lr-fe', type=float, default=3e-4)
    parser.add_argument(
        '--optim',
        type=str,
        default='AdamW',
        choices=('Adam', 'AdamW'),
        help='Optimizer type.',
    )
    parser.add_argument('--weight-decay', type=float, default=0.0)
    parser.add_argument('--clip-temperature', type=float, default=1.0)
    parser.add_argument('--clip-temperature-lr', type=float, default=1e-3)
    parser.add_argument('--nepoch', type=int, default=50)
    parser.add_argument(
        '--early-stopping-patience',
        type=str,
        default='7',
        help='Stop after this many consecutive epochs without validation-loss improvement '
        "(strict improvement = lower loss than the running best). Use 'none' to disable "
        'and train for the full --nepoch.',
    )
    parser.add_argument(
        '--tf-unfreeze-epoch',
        type=int,
        default=None,
        help='Epoch to start training temporal filters (None = always train).',
    )
    parser.add_argument(
        '--lr-temporal-mult',
        type=float,
        default=1.0,
        help='Learning rate multiplier for temporal filter.',
    )
    parser.add_argument(
        '--wd-temporal',
        type=float,
        default=None,
        help='Weight decay for temporal filter (None = use main weight-decay).',
    )
    parser.add_argument(
        '--tf-smooth',
        type=float,
        default=0.0,
        help='Smoothness penalty (L2 of second difference) for temporal filter kernel.',
    )

    # Logging arguments
    parser.add_argument('--logging-project', type=str, default='LISA-MEG')
    parser.add_argument(
        '--run-group',
        type=str,
        required=True,
        help='Run group id for grouping runs (e.g. 5conv-10ch). Stored in config; experiment dir is experiments/<run_group>/<run_name>_<run_id>/.',
    )
    parser.add_argument(
        '--max-branches-to-plot',
        type=int,
        default=20,
        help='Maximum branches to show on filter plots.',
    )
    parser.add_argument(
        '--plot-filter-graphs',
        action=argparse.BooleanOptionalAction,
        default=False,
        help='Plot and save temporal/spatial filter graphs after each epoch. '
        'Disabled by default; spatial graphs require source MEG FIF/BIDS files.',
    )
    parser.add_argument(
        '--experiments-root',
        type=str,
        default=EXPERIMENTS_DIR,
        help='Root directory to save experiment data.',
    )
    parser.add_argument('--image-formats', nargs='+', type=str, default=('png', 'pdf'))
    parser.add_argument(
        '--upload-metrics-csv',
        action=argparse.BooleanOptionalAction,
        default=False,
        help='Upload metrics.csv as ClearML artifact.',
    )
    parser.add_argument(
        '--log-images-to-server',
        action=argparse.BooleanOptionalAction,
        default=False,
        help='Upload figures (temporal/spatial filters) to server (only works if non-local logging is used). Default: False.',
    )
    parser.add_argument(
        '--logger',
        type=str,
        default='local',
        choices=('clearml', 'local'),
        help=(
            'Experiment logger: local (save to disk only; default) or clearml '
            '(requires pip install lisa[clearml]).'
        ),
    )
    parser.add_argument(
        '--save-test-top-k',
        type=int,
        default=20,
        help='Number of top retrieval predictions per test window to dump to '
        'final_test_per_window.npz alongside metrics.csv. rank_of_true is always '
        'saved separately and covers any post-hoc Top-K accuracy.',
    )

    ns = parser.parse_args(argv) if argv is not None else parser.parse_args()
    args = vars(ns)

    if args['n_channels_block'].lower() == 'auto':
        args['n_channels_block'] = args['n_channels_unmix']
    else:
        try:
            args['n_channels_block'] = int(args['n_channels_block'])
        except ValueError:
            parser.error("--n-channels-block must be a positive integer or 'auto'.")
        if args['n_channels_block'] < 1:
            parser.error("--n-channels-block must be a positive integer or 'auto'.")

    if args['seed'].lower() == 'none':
        args['seed'] = None
    else:
        try:
            args['seed'] = int(args['seed'])
        except ValueError:
            parser.error("--seed must be an integer or 'none'.")

    if args['early_stopping_patience'].lower() == 'none':
        args['early_stopping_patience'] = None
    else:
        try:
            args['early_stopping_patience'] = int(args['early_stopping_patience'])
        except ValueError:
            parser.error(
                "--early-stopping-patience must be a positive integer or 'none'."
            )

    def _validate_time_reduction_args(
        *,
        reduction: str,
        output_length: int | None,
        hidden_dim: int | None,
        num_heads: int,
    ) -> None:
        if output_length is not None and output_length <= 0:
            parser.error('--time-reduction-dim must be a positive integer.')
        if hidden_dim is not None and hidden_dim <= 0:
            parser.error('--time-reduction-hidden-dim must be a positive integer.')
        if num_heads <= 0:
            parser.error('--time-reduction-num-heads must be a positive integer.')

        if reduction in ('pca', 'linear', 'adaptive_avg', 'adaptive_max', 'query_attn'):
            if output_length is None:
                parser.error(
                    '--time-reduction-dim is required when --time-reduction is '
                    'pca, linear, adaptive_avg, adaptive_max, or query_attn.'
                )
        elif output_length is not None:
            parser.error(
                '--time-reduction-dim can be used only with pca, linear, '
                'adaptive pooling, or query attention.'
            )

        if reduction not in ('attn', 'gated_attn') and hidden_dim is not None:
            parser.error(
                '--time-reduction-hidden-dim is used only with attn or gated_attn.'
            )

        if reduction != 'query_attn' and num_heads != 1:
            parser.error(
                '--time-reduction-num-heads is used only with --time-reduction=query_attn.'
            )

    if args['feature_reduction_dim'] is not None and args['feature_reduction_dim'] <= 0:
        parser.error('--feature-reduction-dim must be a positive integer.')
    if args['feature_reduction'] == 'none' and args['feature_reduction_dim'] is not None:
        parser.error(
            '--feature-reduction-dim can be used only when --feature-reduction is pca or linear.'
        )
    if args['feature_reduction'] != 'none' and args['feature_reduction_dim'] is None:
        parser.error(
            '--feature-reduction-dim is required when --feature-reduction is pca or linear.'
        )

    _validate_time_reduction_args(
        reduction=args['time_reduction'],
        output_length=args['time_reduction_dim'],
        hidden_dim=args['time_reduction_hidden_dim'],
        num_heads=args['time_reduction_num_heads'],
    )

    if (
        args['feature_reduction'] != 'none'
        and args['time_reduction'] != 'none'
    ):
        parser.error(
            'Feature and time reduction cannot both be active in the same run.'
        )
    if (
        args['feature_reduction'] != 'none'
        and args['feature_reduction_dim'] is not None
        and args['feature_reduction_dim'] > N_FEATURES
    ):
        parser.error(
            f'--feature-reduction-dim cannot exceed the wav2vec feature size ({N_FEATURES}).'
        )

    if args['spatial_dropout_number'] < 0:
        parser.error('--spatial-dropout-number must be a non-negative integer.')
    if args['spatial_dropout_radius'] < 0:
        parser.error('--spatial-dropout-radius must be non-negative.')
    if args['dropout_center_high'] <= args['dropout_center_low']:
        parser.error('--dropout-center-high must be greater than --dropout-center-low.')

    if args['save_test_top_k'] < 1:
        parser.error('--save-test-top-k must be a positive integer.')

    if args['window_tag'] and not args['window_tag'].isalnum():
        parser.error(
            '--window-tag must be alphanumeric with no separators (e.g. "w5"), '
            f'got {args["window_tag"]!r}.'
        )
    if args['window_tag'] and (
        args['feature_reduction'] == 'pca' or args['time_reduction'] == 'pca'
    ):
        parser.error(
            '--window-tag is not supported with PCA reductions yet. Regenerate '
            'window-tagged PCA files first or run the window experiment without PCA.'
        )

    if args['early_stopping_patience'] is not None and args['early_stopping_patience'] < 1:
        parser.error('--early-stopping-patience must be a positive integer when set.')

    # Add hardcoded constants
    if args['feature_reduction'] != 'none':
        args['n_features'] = args['feature_reduction_dim']
    else:
        args['n_features'] = N_FEATURES
    args['time_reduction_input_length'] = None
    args['audio_time_reduction_input_length'] = None
    args['checkpoint'] = CHECKPOINT_NAME

    # Normalize spatial attention: 'none' -> None
    if args['use_spatial_attention'] == 'none':
        args['use_spatial_attention'] = None

    if not args['use_unmixing_layer'] and not args['use_subject_layer']:
        active_input_channels = (
            args['n_channels_attention']
            if args['use_spatial_attention'] is not None
            else N_MEG_CHANNELS
        )
        if active_input_channels != args['n_channels_unmix']:
            parser.error(
                'When both --no-use-unmixing-layer and --no-use-subject-layer are set, '
                'the active input channel count before the temporal filter must equal '
                f'--n-channels-unmix. Got active_input_channels={active_input_channels} '
                f'and n_channels_unmix={args["n_channels_unmix"]}.'
            )

    # Derive run name for display and experiment dir (run_name_run_id)
    args['run_name'] = f'{args["run_group"]}-{args["n_channels_unmix"]}branches'

    # Validate run_group so we never silently mangle it in the logger
    validate_run_group(args['run_group'])

    # Validate and set device
    assert args['device'] == 'cpu' or args['device'].startswith('cuda'), (
        "Device must be 'cpu' or 'cuda[:N]'"
    )
    if args['device'].startswith('cuda') and not torch.cuda.is_available():
        parser.error('CUDA device specified but CUDA is not available.')
    args['device'] = torch.device(args['device'])

    return args


if __name__ == '__main__':
    args = parse_experiment_arguments()
    for arg, val in sorted(args.items()):
        print(f'{arg}: {val}')
